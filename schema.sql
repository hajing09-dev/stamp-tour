-- 2.1 동아리/부스 목록 테이블
CREATE TABLE IF NOT EXISTS public.clubs (
    club_id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    location TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2.2 사용자/운영진 프로필 테이블
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    student_id TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'L1' CHECK (role IN ('L1', 'L2', 'L3')),
    is_approved BOOLEAN NOT NULL DEFAULT true,
    club_id TEXT REFERENCES public.clubs(club_id),
    active_session_id TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2.3 부스별 실시간 OTP 및 상태 관리 테이블
CREATE TABLE IF NOT EXISTS public.clubs_status (
    club_id TEXT PRIMARY KEY REFERENCES public.clubs(club_id),
    current_otp TEXT,
    otp_expires_at TIMESTAMPTZ,
    last_login_at TIMESTAMPTZ DEFAULT now()
);

-- 2.4 학생 스탬프 적립 내역 테이블
CREATE TABLE IF NOT EXISTS public.stamps (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL,
    club_id TEXT NOT NULL REFERENCES public.clubs(club_id),
    created_at TIMESTAMPTZ DEFAULT now(),
    CONSTRAINT stamps_student_id_club_id_key UNIQUE (student_id, club_id)
);

-- 2.5 실시간 보안 감사 및 오류/시도 로그 테이블
CREATE TABLE IF NOT EXISTS public.stamp_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id TEXT NOT NULL,
    club_id TEXT NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2.6 대규모 랭킹 집계 고속화 인덱스
CREATE INDEX IF NOT EXISTS idx_stamps_ranking ON public.stamps(student_id, created_at);

