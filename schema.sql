-- 3.1 현재 로그인 유저의 역할(Role) 조회 헬퍼
CREATE OR REPLACE FUNCTION public.get_my_role()
RETURNS TEXT
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT role FROM public.users WHERE student_id = auth.jwt()->>'email' LIMIT 1;
$$;

-- 3.2 현재 로그인 유저의 담당 부스(club_id) 조회 헬퍼
CREATE OR REPLACE FUNCTION public.get_my_club()
RETURNS TEXT
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'public'
AS $$
  SELECT club_id FROM public.users WHERE student_id = auth.jwt()->>'email' LIMIT 1;
$$;

